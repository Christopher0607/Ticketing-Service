// Bundles db/*.sql (and Supabase's public root CA) into lib/migrations.generated.ts so serverless
// functions can apply migrations without reading files. Runs automatically before `next build`.
import { readFile, readdir, writeFile } from "node:fs/promises";

const dir = new URL("../db/", import.meta.url);
const names = (await readdir(dir)).filter((file) => /^\d+_.+\.sql$/.test(file)).sort();
const migrations = await Promise.all(names.map(async (name) => ({ name, sql: await readFile(new URL(name, dir), "utf8") })));
const post = await readFile(new URL("post-migrate.sql", dir), "utf8");
const ca = await readFile(new URL("supabase-root-2021.crt", dir), "utf8");
const output = `// Generated by scripts/bundle-migrations.mjs from db/. Do not edit by hand.
export const migrations: { name: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};

export const postMigrateSql = ${JSON.stringify(post)};

/** Supabase Root 2021 CA (public certificate), used to verify TLS to Supabase databases. */
export const supabaseRootCa = ${JSON.stringify(ca)};
`;
const target = new URL("../lib/migrations.generated.ts", import.meta.url);
let current = "";
try { current = await readFile(target, "utf8"); } catch { /* first run */ }
if (current !== output) await writeFile(target, output);
console.log(`Bundled ${migrations.length} migrations.`);
